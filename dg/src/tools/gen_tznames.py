"""gen_tznames.py -- the time zone abbreviation sets, compiled in.

  gen_tznames.py DIR > tznames_builtin.c

Writes C that holds the text of each set in DIR (src/timezone/tznames)
whose name timezone_abbreviations can give: Default, Australia and India,
each a name of letters alone. The .txt files beside them are lists to
copy from, which PostgreSQL does not load either. digres has no
installation to read them from (WORKNOTE.md step 199); tzparser.c reads
this text as it read the files, through tzparser_builtin_set().
"""
import os
import sys


def c_string(text):
    """text as C string literals, one a line."""
    out = []
    for line in text.splitlines(keepends=True):
        esc = line.replace('\\', '\\\\').replace('"', '\\"')
        esc = esc.replace('\t', '\\t').replace('\n', '\\n')
        out.append('    "%s"' % esc)
    return '\n'.join(out) if out else '    ""'


def main():
    """Write the C for the sets in sys.argv[1]."""
    src = sys.argv[1]
    # README is all letters too, and no set: PostgreSQL does not install it.
    names = sorted(n for n in os.listdir(src)
                   if n.isalpha() and n != 'README')
    w = sys.stdout.write
    w('/*\n * tznames_builtin.c\n'
      ' *\t  The time zone abbreviation sets, compiled in.\n'
      ' *\n * Generated by src/tools/gen_tznames.py from src/timezone/tznames:'
      '\n * do not edit.\n */\n')
    w('#include "postgres.h"\n\n#include "utils/tzparser.h"\n\n')
    w('/* A set: its name, as timezone_abbreviations gives it, and its'
      ' text. */\n')
    w('typedef struct tzparser_set_t {\n  const char *name;\n'
      '  const char *text;\n} tzparser_set_t;\n\n')
    w('static const tzparser_set_t tzparser_sets[] = {\n')
    for name in names:
        with open(os.path.join(src, name), encoding='utf-8') as f:
            text = f.read()
        w('    {"%s",\n%s},\n' % (name, c_string(text)))
    w('};\n\n')
    w('/* The text of the set named name, or NULL if there is none. */\n')
    w('const char *tzparser_builtin_set(const char *name) {\n'
      '  for (const tzparser_set_t &set : tzparser_sets)\n'
      '    if (strcmp(set.name, name) == 0)\n'
      '      return set.text;\n'
      '  return NULL;\n}\n')


if __name__ == '__main__':
    main()
