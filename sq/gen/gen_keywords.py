#!/usr/bin/env python3
"""gen_keywords.py -- write a perfect hash over PostgreSQL's keywords.

    gen/gen_keywords.py > build/gen/keyword_hash.h

The input is spec/kwlist.h. The output is one function,
keyword_hash(key, keylen), which maps each keyword to its number in
that list, in whatever case its ASCII letters are, and maps anything
else to some number, in range or out. One comparison with the keyword
of that number then settles it: no probing, and no collisions.

This is PostgreSQL's src/tools/PerfectHash.pm, in Python: the same
search, in the same order, for the same function, so that sq's hash
over a given kwlist.h is PostgreSQL's. The method is from Czech,
Havas and Majewski, "An Optimal Algorithm for Generating Minimal
Perfect Hash Functions". Each keyword is an edge between two vertices,
its two hash values; if the graph has no cycle, the vertices can be
numbered so that an edge's two numbers add up to the keyword's.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent


def read_keywords():
    """The keywords of spec/kwlist.h, in its order."""
    text = (ROOT / "spec" / "kwlist.h").read_text()
    return re.findall(r'^PG_KEYWORD\("(\w+)"', text, flags=re.M)


def calc_hash(key, mult, seed):
    """Hash key as the generated function will, folding case."""
    result = seed
    for ch in key.encode():
        result = (result * mult + (ch | 0x20)) % 4294967296
    return result


def construct_hash_table(keys, mult1, mult2, seed1, seed2):
    """Try one pair of hash functions; the table, or None if it cycles."""
    nedges = len(keys)
    nverts = 2 * nedges + 1
    # A table size the multipliers divide would hash badly.
    while nverts % mult1 == 0 or nverts % mult2 == 0:
        nverts += 1

    edges = []
    for kw in keys:
        h1 = calc_hash(kw, mult1, seed1) % nverts
        h2 = calc_hash(kw, mult2, seed2) % nverts
        if h1 == h2:
            return None
        edges.append((h1, h2))

    # Each vertex's edges, in the order they were added.
    incident = [dict() for _ in range(nverts)]
    for e, (left, right) in enumerate(edges):
        incident[left][e] = True
        incident[right][e] = True

    # Peel off vertices of degree one. If every edge comes off, there
    # is no cycle, and the reverse of the peeling order is an order in
    # which each edge meets at least one vertex not yet numbered.
    order = []
    for start in range(nverts):
        v = start
        while len(incident[v]) == 1:
            e = next(iter(incident[v]))
            del incident[v][e]
            v2 = edges[e][0] if edges[e][0] != v else edges[e][1]
            del incident[v2][e]
            order.insert(0, e)
            v = v2
    if len(order) != nedges:
        return None

    table = [0] * nverts
    visited = [False] * nverts
    for e in order:
        left, right = edges[e]
        if not visited[left]:
            table[left] = e - table[right]
        else:
            assert not visited[right], "doubly used hash table entry"
            table[right] = e - table[left]
        visited[left] = visited[right] = True

    # A vertex no keyword touches gets a value that takes any sum it
    # is part of out of range.
    assert min(table) >= -0x7FFF and max(table) <= 0x7FFF
    assert min(table) + 0x7FFF >= nedges
    return [t if seen else 0x7FFF for t, seen in zip(table, visited)]


def find_hash(keys):
    """Search PostgreSQL's parameters, in its order, for a table."""
    mult1 = 257
    for seed1 in range(10):
        for seed2 in range(10):
            for mult2 in (17, 31, 127, 8191):
                table = construct_hash_table(keys, mult1, mult2, seed1, seed2)
                if table is not None:
                    return mult1, mult2, seed1, seed2, table
    sys.exit("failed to generate perfect hash")


def main():
    """Write build/gen/keyword_hash.h to standard output."""
    keys = read_keywords()
    mult1, mult2, seed1, seed2, table = find_hash(keys)
    for i, kw in enumerate(keys):
        a = calc_hash(kw, mult1, seed1) % len(table)
        b = calc_hash(kw, mult2, seed2) % len(table)
        assert table[a] + table[b] == i, kw

    w = sys.stdout.write
    w("/*\n * keyword_hash.h -- a perfect hash over spec/kwlist.h.\n *\n")
    w(" * GENERATED by gen/gen_keywords.py. Do not edit.\n */\n\n")
    w(f"/* How many keywords there are, and the longest, in bytes. */\n")
    w(f"static const int keyword_hash_count = {len(keys)};\n")
    w(f"static const size_t keyword_max_len = {max(map(len, keys))};\n\n")
    w("/*\n * The number of the keyword the keylen bytes at key may be:\n")
    w(" * right if they are a keyword, in any case, and otherwise any\n")
    w(" * number, in range or not.\n */\n")
    w("static int keyword_hash(const void *key, size_t keylen) {\n")
    w(f"  static const int16_t h[{len(table)}] = {{")
    for i, t in enumerate(table):
        w(("\n      " if i % 8 == 0 else " ") + f"{t},")
    w("\n  };\n\n")
    w("  const unsigned char *k = static_cast<const unsigned char *>(key);\n")
    w(f"  uint32_t a = {seed1};\n  uint32_t b = {seed2};\n\n")
    w("  while (keylen--) {\n")
    w("    // Fold ASCII upper case to lower; what else this changes is\n")
    w("    // settled by the comparison that follows a lookup.\n")
    w("    unsigned char c = *k++ | 0x20;\n\n")
    w(f"    a = a * {mult1} + c;\n    b = b * {mult2} + c;\n  }}\n")
    w(f"  return h[a % {len(table)}] + h[b % {len(table)}];\n}}\n")


if __name__ == "__main__":
    main()
